// Renders webdriver-ts/results/*.json as a Markdown comparison table.
// Usage (repo root): node webdriver-ts/results-to-markdown.mjs > RESULTS.md

import {readdirSync, readFileSync} from 'node:fs';
import {join} from 'node:path';

const results_dir = join(import.meta.dirname, 'results');

// From `cpuBenchmarkInfosArray` and `throttlingFactors` in src/benchmarksCommon.ts.
const cpu_benchmarks = [
	['01_run1k', 'create rows', 'creating 1,000 rows'],
	['02_replace1k', 'replace all rows', 'updating all 1,000 rows'],
	['03_update10th1k_x16', 'partial update', 'updating every 10th row of 1,000 rows', 4],
	['04_select1k', 'select row', 'highlighting a selected row', 4],
	['05_swap1k', 'swap rows', 'swap 2 rows for a table with 1,000 rows', 4],
	['06_remove-one-1k', 'remove row', 'removing one row', 2],
	['07_create10k', 'create many rows', 'creating 10,000 rows'],
	['08_create1k-after1k_x2', 'append rows', 'appending 1,000 to a table of 1,000 rows'],
	['09_clear1k_x8', 'clear rows', 'clearing a table with 1,000 rows', 4],
];
const memory_benchmarks = [
	['21_ready-memory', 'ready memory', 'after page load'],
	['22_run-memory', 'run memory', 'after adding 1,000 rows'],
	['25_run-clear-memory', 'create/clear 5 cycles', 'after creating and clearing 1,000 rows 5 times'],
];
const startup_benchmarks = [
	['41_size-uncompressed', 'size uncompressed', 'kB'],
	['42_size-compressed', 'size compressed', 'kB'],
	['43_first-paint', 'first paint', 'ms'],
];

const results = new Map(); // framework -> benchmark id -> stats
for (const file of readdirSync(results_dir)) {
	if (!file.endsWith('.json')) continue;
	const r = JSON.parse(readFileSync(join(results_dir, file), 'utf8'));
	const framework = r.framework.replace(/-keyed$/, '');
	const stats = r.values.total ?? r.values.DEFAULT;
	if (!results.has(framework)) results.set(framework, new Map());
	results.get(framework).set(r.benchmark, stats);
}

const mean = (framework, id) => results.get(framework).get(id)?.mean;

const geometric_mean = (values) => Math.exp(values.reduce((s, v) => s + Math.log(v), 0) / values.length);

// Factor relative to the fastest framework, as the results UI shows it.
const factors = (ids, framework) =>
	ids.map((id) => {
		const best = Math.min(...[...results.keys()].map((f) => mean(f, id) ?? Infinity));
		return mean(framework, id) / best;
	});

const cpu_ids = cpu_benchmarks.map(([id]) => id);
const frameworks = [...results.keys()].sort(
	(a, b) => geometric_mean(factors(cpu_ids, a)) - geometric_mean(factors(cpu_ids, b)),
);

const table = (rows) => {
	const header = ['', ...frameworks.map((f) => `\`${f}\``)];
	return [header, header.map(() => '---'), ...rows].map((cells) => `| ${cells.join(' | ')} |`).join('\n');
};

const label_cell = (label, note) => `**${label}**<br><sub>${note}</sub>`;

const cpu_rows = cpu_benchmarks.map(([id, label, description, throttle]) => {
	const note = throttle ? `${description}, ${throttle}× CPU slowdown` : description;
	const best = Math.min(...frameworks.map((f) => mean(f, id) ?? Infinity));
	return [
		label_cell(label, note),
		...frameworks.map((f) => {
			const s = results.get(f).get(id);
			if (!s) return '–';
			return `${s.mean.toFixed(1)} ±${s.stddev.toFixed(1)}<br><sub>${(s.mean / best).toFixed(2)}×</sub>`;
		}),
	];
});
cpu_rows.push([
	label_cell('geometric mean', 'of the factors above'),
	...frameworks.map((f) => `**${geometric_mean(factors(cpu_ids, f)).toFixed(2)}×**`),
]);

const single_rows = (benchmarks, unit) =>
	benchmarks.map(([id, label, note]) => [
		label_cell(label, unit ? note : `${note}, MB`),
		...frameworks.map((f) => {
			const m = mean(f, id);
			return m == null ? '–' : m.toFixed(1);
		}),
	]);

const iterations = Math.max(...[...results.values()].flatMap((m) => [...m.values()].map((s) => s.values.length)));

console.log(`# Results

Keyed implementations, sorted by the geometric mean of the CPU factors.
Generated by \`node webdriver-ts/results-to-markdown.mjs\` from \`webdriver-ts/results/\`.

## Duration

Mean ± standard deviation in ms over up to ${iterations} iterations, with the
factor relative to the fastest implementation below each value.

${table(cpu_rows)}

## Memory

Single measurement in MB.

${table(single_rows(memory_benchmarks))}

## Size and startup

Single measurement: bundle size in kB, first paint in ms.

${table(single_rows(startup_benchmarks, true))}
`);
